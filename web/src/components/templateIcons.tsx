type Desc = {
  id?: string
  name?: string
  language?: string
  tags?: string[]
  category?: string
  image?: string
}

function resolveGlyphKey(d: Desc): string | null {
  const id = (d.id ?? '').toLowerCase()
  const name = (d.name ?? '').toLowerCase()
  const lang = (d.language ?? '').toLowerCase()
  const tags = (d.tags ?? []).map(t => t.toLowerCase())
  const hay = `${id} ${name} ${tags.join(' ')}`
  const has = (...w: string[]) => w.some(x => hay.includes(x))

  // Checked before the generic browser match below: playwright's own tags
  // include "browser", which would otherwise resolve to the chrome glyph.
  if (has('playwright')) return 'playwright'
  if (has('desktop', 'computer-use', 'gui', 'vnc', 'chromium', 'chrome', 'browser')) return 'chrome'

  if (has('jupyter') && !has('python')) return 'jupyter'
  if (lang === 'python' || has('python', 'code-interpreter', 'fastapi', 'flask', 'django', 'jupyter')) return 'python'

  if (lang === 'typescript' || has('typescript')) return 'typescript'
  if (lang === 'node' || has('node', 'javascript', 'next', 'deno', 'bun', 'express')) return 'node'

  if (lang === 'go' || lang === 'golang' || has('golang')) return 'go'
  if (lang === 'rust' || has('rust', 'cargo')) return 'rust'

  if (d.image || has('docker', 'container')) return 'docker'

  if (id === 'base' || has('minimal', 'debian', 'bash', 'shell')) return 'shell'

  return null
}

function initials(d: Desc): string {
  const s = (d.name || d.id || '?').trim()
  const parts = s.split(/[\s\-_]+/).filter(Boolean)
  if (parts.length >= 2) return (parts[0][0] + parts[1][0]).toUpperCase()
  return s.slice(0, 2).toUpperCase()
}

export function TemplateIcon({
  t,
  template,
  desc,
}: {
  t?: Template
  template?: string
  desc?: Desc
}) {
  const d: Desc = desc ?? (t ? { id: t.id, name: t.name, language: t.language, tags: t.tags, category: t.category, image: t.image } : { id: template })
  const key = resolveGlyphKey(d)
  const glyph = key ? GLYPHS[key] : null

  if (!glyph) {
    return <span className="tico tico-txt">{initials(d)}</span>
  }
  return (
    <span className="tico" style={glyph.color !== 'inherit' ? { color: glyph.color } : undefined}>
      <svg viewBox={glyph.vb} className="tico-svg" role="img" aria-hidden="true">
        {glyph.body}
      </svg>
    </span>
  )
}
