// Session environment construction. envd's own env is a bare init environment,
// so sessions are layered, later wins: envd process env, forced root identity,
// /etc/sandbox-env (the image's Config.Env), /etc/template.env (operator
// override), then per-request env.
package main

import (
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// templateEnvDir holds sandbox-env and template.env; a var so tests can redirect it.
var templateEnvDir = "/etc"

// profileDir receives the login-shell drop-in; a var so tests can redirect it.
var profileDir = "/etc/profile.d"

const defaultPath = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"

// mergeTemplateEnv overlays env onto dir/template.env (0600, sorted K=V).
// Values are written raw because readEnvFile is a raw K=V parser: quoting
// here would put the quotes into $VAR. ponytail: a value with a newline
// cannot round-trip through a line-oriented file; refuse it rather than corrupt the file.
func mergeTemplateEnv(dir string, env map[string]string) error {
	path := filepath.Join(dir, "template.env")
	merged := readEnvFile(path)
	for k, v := range env {
		if strings.ContainsAny(v, "\n\r") {
			return fmt.Errorf("env %s: value contains a newline", k)
		}
		merged[k] = v
	}
	var b strings.Builder
	for _, k := range slices.Sorted(maps.Keys(merged)) {
		b.WriteString(k + "=" + merged[k] + "\n")
	}
	return os.WriteFile(path, []byte(b.String()), 0600)
}

// buildSessionEnv returns the environment for a new exec/terminal session.
func buildSessionEnv(reqEnv map[string]string) []string {
	return buildSessionEnvFrom(templateEnvDir, reqEnv)
}

// buildSessionEnvFrom is buildSessionEnv with an injectable env directory for tests.
func buildSessionEnvFrom(dir string, reqEnv map[string]string) []string {
	env := map[string]string{}

	for _, kv := range os.Environ() {
		if k, v, ok := strings.Cut(kv, "="); ok {
			env[k] = v
		}
	}

	env["HOME"] = "/root"
	env["USER"] = "root"
	env["LOGNAME"] = "root"
	env["SHELL"] = "/bin/bash"
	if env["LANG"] == "" {
		env["LANG"] = "C.UTF-8"
	}
	if env["PATH"] == "" {
		env["PATH"] = defaultPath
	}

	for k, v := range readEnvFile(filepath.Join(dir, "sandbox-env")) {
		env[k] = v
	}

	for k, v := range readEnvFile(filepath.Join(dir, "template.env")) {
		env[k] = v
	}

	// The sandbox's own identity (identity.go). Read per session, not at boot:
	// on Docker it is copied in after envd started.
	for k, v := range readEnvFile(filepath.Join(identityDir, "env")) {
		env[k] = v
	}

	// Set only once a display exists, so a GUI program started by exec or from
	// the web terminal lands on the screen someone is watching. Before reqEnv:
	// a caller naming its own DISPLAY still wins.
	if desktopUp.Load() {
		env["DISPLAY"] = desktopDisplay
	}

	for k, v := range reqEnv {
		env[k] = v
	}

	out := make([]string, 0, len(env))
	for _, k := range slices.Sorted(maps.Keys(env)) {
		out = append(out, k+"="+env[k])
	}
	return out
}

// writeProfileDropIn writes a profile.d script re-exporting the baked template
// env, because Debian's /etc/profile resets PATH for login shells after envd set it.
// It also sources the sandbox identity env at shell start rather than baking it
// in: the identity arrives after boot (credential channel, or docker cp).
func writeProfileDropIn(envDir, profileDir string) error {
	vars := readEnvFile(filepath.Join(envDir, "sandbox-env"))
	for k, v := range readEnvFile(filepath.Join(envDir, "template.env")) {
		vars[k] = v
	}
	var b strings.Builder
	b.WriteString("# generated by envd at boot — re-exports the baked template env\n")
	b.WriteString("# after /etc/profile's PATH reset (see cmd/envd/env.go)\n")
	for _, k := range slices.Sorted(maps.Keys(vars)) {
		b.WriteString("export " + k + "='" + strings.ReplaceAll(vars[k], "'", `'\''`) + "'\n")
	}
	b.WriteString(identityProfileLine(identityDir))
	if err := os.MkdirAll(profileDir, 0755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(profileDir, "zz-pilldrops-env.sh"), []byte(b.String()), 0644)
}

// identityProfileLine sources the sandbox identity env into a login shell.
// The same line is what the docker runtime drops into /etc/profile.d itself,
// because there envd runs unprivileged and cannot write the drop-in.
func identityProfileLine(dir string) string {
	return "[ -r " + dir + "/env ] && { set -a; . " + dir + "/env; set +a; }\n"
}

// readEnvFile parses KEY=VALUE lines, skipping blanks, comments and malformed
// lines. A missing file yields an empty map.
func readEnvFile(path string) map[string]string {
	out := map[string]string{}
	data, err := os.ReadFile(path)
	if err != nil {
		return out
	}
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, v, ok := strings.Cut(line, "="); ok && k != "" {
			out[strings.TrimSpace(k)] = v
		}
	}
	return out
}
